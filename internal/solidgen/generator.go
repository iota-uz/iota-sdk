// Package solidgen discovers Go solid.Import declarations and generates the
// colocated TypeScript bindings plus one lazy feature catalog for a consumer.
package solidgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"reflect"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/iota-uz/iota-sdk/pkg/clienthost/solid"
	"golang.org/x/tools/go/packages"
)

const (
	solidImportPath = "github.com/iota-uz/iota-sdk/pkg/clienthost/solid"
	generatedHeader = "// Code generated by iota-solid. DO NOT EDIT.\n"
)

type Config struct {
	ModuleRoot string
	Catalog    string
	Check      bool
}

type Result struct {
	Features int
	Files    []string
}

type candidate struct {
	goFile      string
	line        int
	source      string
	generated   string
	component   types.Type
	packagePath string
	methods     []method
}

type method struct {
	name        string
	kind        string
	request     types.Type
	response    types.Type
	cacheable   bool
	maxRetries  int
	invalidates []string
}

func Run(cfg Config) (Result, error) {
	root, err := filepath.Abs(cfg.ModuleRoot)
	if err != nil {
		return Result{}, err
	}
	catalog := cfg.Catalog
	if strings.TrimSpace(catalog) == "" {
		catalog = "web/src/solid-features.generated.ts"
	}
	if !filepath.IsAbs(catalog) {
		catalog = filepath.Join(root, catalog)
	}
	candidates, err := discover(root)
	if err != nil {
		return Result{}, err
	}
	outputs := make(map[string][]byte, len(candidates)+1)
	ids := make(map[string]string, len(candidates))
	for _, feature := range candidates {
		id := solid.FeatureID(feature.packagePath, feature.source)
		if previous, exists := ids[id]; exists {
			return Result{}, fmt.Errorf("%s:%d: duplicate Solid feature %s (already declared at %s)", feature.goFile, feature.line, id, previous)
		}
		ids[id] = fmt.Sprintf("%s:%d", feature.goFile, feature.line)
		contents, err := emitBindings(feature)
		if err != nil {
			return Result{}, fmt.Errorf("%s:%d: %w", feature.goFile, feature.line, err)
		}
		outputs[feature.generated] = []byte(contents)
	}
	catalogContents, err := emitCatalog(catalog, candidates)
	if err != nil {
		return Result{}, err
	}
	outputs[catalog] = []byte(catalogContents)
	if err := reconcile(root, outputs, cfg.Check); err != nil {
		return Result{}, err
	}
	files := make([]string, 0, len(outputs))
	for file := range outputs {
		relative, relErr := filepath.Rel(root, file)
		if relErr != nil {
			relative = file
		}
		files = append(files, filepath.ToSlash(relative))
	}
	sort.Strings(files)
	return Result{Features: len(candidates), Files: files}, nil
}

func discover(root string) ([]candidate, error) {
	byDirectory := make(map[string][]candidate)
	err := filepath.WalkDir(root, func(file string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			switch entry.Name() {
			case ".git", "node_modules", "vendor", "dist", ".worktrees":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") || strings.HasSuffix(entry.Name(), "_templ.go") {
			return nil
		}
		found, err := scanFile(file)
		if err != nil {
			return err
		}
		if len(found) > 0 {
			byDirectory[filepath.Dir(file)] = append(byDirectory[filepath.Dir(file)], found...)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	directories := make([]string, 0, len(byDirectory))
	for directory := range byDirectory {
		directories = append(directories, directory)
	}
	sort.Strings(directories)
	result := make([]candidate, 0)
	for _, directory := range directories {
		resolved, err := resolvePackage(directory, byDirectory[directory])
		if err != nil {
			return nil, err
		}
		result = append(result, resolved...)
	}
	sort.Slice(result, func(i, j int) bool {
		if result[i].goFile == result[j].goFile {
			return result[i].line < result[j].line
		}
		return result[i].goFile < result[j].goFile
	})
	return result, nil
}

func scanFile(file string) ([]candidate, error) {
	set := token.NewFileSet()
	node, err := parser.ParseFile(set, file, nil, parser.ImportsOnly)
	if err != nil {
		return nil, err
	}
	aliases := make(map[string]struct{})
	for _, spec := range node.Imports {
		pathValue, err := strconv.Unquote(spec.Path.Value)
		if err != nil || pathValue != solidImportPath {
			continue
		}
		name := "solid"
		if spec.Name != nil {
			name = spec.Name.Name
		}
		if name != "_" && name != "." {
			aliases[name] = struct{}{}
		} else if name == "." {
			return nil, fmt.Errorf("%s: dot-importing %s is unsupported; use a package qualifier", file, solidImportPath)
		}
	}
	if len(aliases) == 0 {
		return nil, nil
	}
	node, err = parser.ParseFile(set, file, nil, 0)
	if err != nil {
		return nil, err
	}
	result := make([]candidate, 0)
	var scanErr error
	ast.Inspect(node, func(current ast.Node) bool {
		if scanErr != nil {
			return false
		}
		call, ok := current.(*ast.CallExpr)
		if !ok || genericCallName(call.Fun, aliases) != "Import" {
			return true
		}
		if len(call.Args) == 0 {
			position := set.Position(call.Pos())
			scanErr = fmt.Errorf("%s:%d: solid.Import requires a static ./path.tsx source", file, position.Line)
			return false
		}
		literal, ok := call.Args[0].(*ast.BasicLit)
		if !ok || literal.Kind != token.STRING {
			position := set.Position(call.Pos())
			scanErr = fmt.Errorf("%s:%d: solid.Import source must be a string literal", file, position.Line)
			return false
		}
		source, unquoteErr := strconv.Unquote(literal.Value)
		if unquoteErr != nil {
			position := set.Position(call.Pos())
			scanErr = fmt.Errorf("%s:%d: solid.Import source is invalid: %w", file, position.Line, unquoteErr)
			return false
		}
		position := set.Position(call.Pos())
		clean := path.Clean(source)
		if strings.TrimSpace(source) != source || !strings.HasPrefix(source, "./") || path.Ext(source) != ".tsx" || clean == "." || clean == ".." || strings.HasPrefix(clean, "../") {
			scanErr = fmt.Errorf("%s:%d: solid.Import source %q must be a clean relative ./path.tsx inside the declaring Go package", file, position.Line, source)
			return false
		}
		result = append(result, candidate{goFile: file, line: position.Line, source: source})
		return true
	})
	if scanErr != nil {
		return nil, scanErr
	}
	return result, nil
}

func resolvePackage(directory string, candidates []candidate) ([]candidate, error) {
	loaded, err := packages.Load(&packages.Config{
		Dir:  directory,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedDeps,
	}, ".")
	if err != nil {
		return nil, err
	}
	if packages.PrintErrors(loaded) > 0 || len(loaded) != 1 {
		return nil, fmt.Errorf("load Go package %s: expected one package without errors", directory)
	}
	pkg := loaded[0]
	aliasesByFile := make(map[string]map[string]struct{})
	for index, syntax := range pkg.Syntax {
		file := filepath.Clean(pkg.CompiledGoFiles[index])
		aliases := make(map[string]struct{})
		for _, spec := range syntax.Imports {
			pathValue, _ := strconv.Unquote(spec.Path.Value)
			if pathValue != solidImportPath {
				continue
			}
			name := "solid"
			if spec.Name != nil {
				name = spec.Name.Name
			}
			aliases[name] = struct{}{}
		}
		aliasesByFile[file] = aliases
	}
	for index := range candidates {
		candidate := &candidates[index]
		candidate.packagePath = pkg.PkgPath
		candidate.generated = strings.TrimSuffix(filepath.Join(filepath.Dir(candidate.goFile), candidate.source), ".tsx") + ".solid.generated.ts"
		if _, err := os.Stat(strings.TrimSuffix(candidate.generated, ".solid.generated.ts") + ".tsx"); err != nil {
			return nil, fmt.Errorf("%s:%d: Solid source %q: %w", candidate.goFile, candidate.line, candidate.source, err)
		}
		matched := false
		for syntaxIndex, syntax := range pkg.Syntax {
			file := filepath.Clean(pkg.CompiledGoFiles[syntaxIndex])
			if file != filepath.Clean(candidate.goFile) {
				continue
			}
			aliases := aliasesByFile[file]
			ast.Inspect(syntax, func(current ast.Node) bool {
				call, ok := current.(*ast.CallExpr)
				if !ok || pkg.Fset.Position(call.Pos()).Line != candidate.line || genericCallName(call.Fun, aliases) != "Import" {
					return true
				}
				typeExpressions := genericTypeArguments(call.Fun)
				if len(typeExpressions) != 1 {
					return false
				}
				candidate.component = pkg.TypesInfo.TypeOf(typeExpressions[0])
				candidate.methods, err = resolveMethods(pkg, call, aliases)
				if err != nil {
					return false
				}
				matched = true
				return false
			})
			if err != nil {
				return nil, fmt.Errorf("%s:%d: %w", candidate.goFile, candidate.line, err)
			}
		}
		if !matched || candidate.component == nil {
			return nil, fmt.Errorf("%s:%d: cannot resolve solid.Import type argument", candidate.goFile, candidate.line)
		}
	}
	return candidates, nil
}

func resolveMethods(pkg *packages.Package, importCall *ast.CallExpr, aliases map[string]struct{}) ([]method, error) {
	methods := make([]method, 0)
	for _, argument := range importCall.Args[1:] {
		withRPC, ok := argument.(*ast.CallExpr)
		if !ok || genericCallName(withRPC.Fun, aliases) != "WithRPC" {
			continue
		}
		for _, methodArgument := range withRPC.Args {
			call, ok := methodArgument.(*ast.CallExpr)
			if !ok {
				return nil, errors.New("solid.WithRPC accepts only solid.Query or solid.Action declarations")
			}
			kind := strings.ToLower(genericCallName(call.Fun, aliases))
			if kind != "query" && kind != "action" {
				return nil, errors.New("solid.WithRPC accepts only solid.Query or solid.Action declarations")
			}
			typeArguments := genericTypeArguments(call.Fun)
			if len(typeArguments) != 2 || len(call.Args) == 0 {
				return nil, fmt.Errorf("solid.%s requires request/response types and a method name", genericCallName(call.Fun, aliases))
			}
			nameLiteral, ok := call.Args[0].(*ast.BasicLit)
			if !ok || nameLiteral.Kind != token.STRING {
				return nil, fmt.Errorf("solid.%s method name must be a string literal", genericCallName(call.Fun, aliases))
			}
			name, unquoteErr := strconv.Unquote(nameLiteral.Value)
			if unquoteErr != nil || strings.TrimSpace(name) == "" {
				return nil, fmt.Errorf("solid.%s method name must not be empty", genericCallName(call.Fun, aliases))
			}
			resolved := method{name: name, kind: kind, request: pkg.TypesInfo.TypeOf(typeArguments[0]), response: pkg.TypesInfo.TypeOf(typeArguments[1])}
			for _, optionArgument := range call.Args[1:] {
				option, ok := optionArgument.(*ast.CallExpr)
				if !ok {
					continue
				}
				switch genericCallName(option.Fun, aliases) {
				case "Cacheable":
					if kind != "query" {
						return nil, fmt.Errorf("solid.Cacheable is valid only for query %q", name)
					}
					resolved.cacheable = true
					if len(option.Args) != 1 {
						return nil, fmt.Errorf("solid.Cacheable for %q requires one retry count", name)
					}
					value, ok := pkg.TypesInfo.Types[option.Args[0]]
					if !ok || value.Value == nil {
						return nil, fmt.Errorf("solid.Cacheable retry count for %q must be a constant integer", name)
					}
					parsed, parseErr := strconv.Atoi(value.Value.ExactString())
					if parseErr != nil || parsed < 0 || parsed > 3 {
						return nil, fmt.Errorf("solid.Cacheable retry count for %q must be between 0 and 3", name)
					}
					resolved.maxRetries = parsed
				case "Invalidates":
					if kind != "action" {
						return nil, fmt.Errorf("solid.Invalidates is valid only for action %q", name)
					}
					for _, invalidation := range option.Args {
						literal, ok := invalidation.(*ast.BasicLit)
						if !ok || literal.Kind != token.STRING {
							return nil, fmt.Errorf("solid.Invalidates targets for %q must be string literals", name)
						}
						value, valueErr := strconv.Unquote(literal.Value)
						if valueErr != nil || strings.TrimSpace(value) == "" {
							return nil, fmt.Errorf("solid.Invalidates target for %q must not be empty", name)
						}
						resolved.invalidates = append(resolved.invalidates, value)
					}
				}
			}
			methods = append(methods, resolved)
		}
	}
	byName := make(map[string]string, len(methods))
	queries := make(map[string]struct{}, len(methods))
	for _, rpcMethod := range methods {
		if previous, exists := byName[rpcMethod.name]; exists {
			return nil, fmt.Errorf("duplicate RPC method %q (%s and %s)", rpcMethod.name, previous, rpcMethod.kind)
		}
		byName[rpcMethod.name] = rpcMethod.kind
		if rpcMethod.kind == "query" {
			queries[rpcMethod.name] = struct{}{}
		}
	}
	for _, rpcMethod := range methods {
		for _, invalidated := range rpcMethod.invalidates {
			if _, exists := queries[invalidated]; !exists {
				return nil, fmt.Errorf("action %q invalidates unknown query %q", rpcMethod.name, invalidated)
			}
		}
	}
	return methods, nil
}

func genericCallName(expression ast.Expr, aliases map[string]struct{}) string {
	for {
		switch typed := expression.(type) {
		case *ast.IndexExpr:
			expression = typed.X
		case *ast.IndexListExpr:
			expression = typed.X
		case *ast.SelectorExpr:
			identifier, ok := typed.X.(*ast.Ident)
			if ok {
				if _, exists := aliases[identifier.Name]; exists {
					return typed.Sel.Name
				}
			}
			return ""
		default:
			return ""
		}
	}
}

func genericTypeArguments(expression ast.Expr) []ast.Expr {
	switch typed := expression.(type) {
	case *ast.IndexExpr:
		return []ast.Expr{typed.Index}
	case *ast.IndexListExpr:
		return typed.Indices
	default:
		return nil
	}
}

func emitBindings(feature candidate) (string, error) {
	emitter := typeEmitter{active: make(map[types.Type]bool)}
	props, err := emitter.emit(feature.component)
	if err != nil {
		return "", fmt.Errorf("generate Props: %w", err)
	}
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("import type { Component } from 'solid-js'\n")
	output.WriteString("import type { RPCMethodContract, SolidRouteProps } from '@iota-uz/sdk/solid'\n")
	componentImport := "./" + strings.TrimSuffix(filepath.Base(feature.generated), ".solid.generated.ts")
	output.WriteString("import Screen from ")
	output.WriteString(strconv.Quote(componentImport))
	output.WriteString("\n\nexport type Props = ")
	output.WriteString(props)
	output.WriteString("\n\n")
	if len(feature.methods) > 0 {
		output.WriteString("export interface RPC {\n")
		for _, contract := range feature.methods {
			request, requestErr := emitter.emit(contract.request)
			if requestErr != nil {
				return "", fmt.Errorf("generate %s request: %w", contract.name, requestErr)
			}
			response, responseErr := emitter.emit(contract.response)
			if responseErr != nil {
				return "", fmt.Errorf("generate %s response: %w", contract.name, responseErr)
			}
			fmt.Fprintf(&output, "  %q: { params: %s; result: %s }\n", contract.name, request, response)
		}
		output.WriteString("}\n\nexport const rpcContracts = {\n")
		for _, contract := range feature.methods {
			fmt.Fprintf(&output, "  %q: { namespace: %q, method: %q, kind: %q, cacheable: %t, maxRetries: %d, invalidates: %s },\n", contract.name, namespace(contract.name), contract.name, map[string]string{"query": "query", "action": "mutation"}[contract.kind], contract.cacheable, contract.maxRetries, stringArray(contract.invalidates))
		}
		output.WriteString("} as const satisfies Record<keyof RPC, RPCMethodContract>\n\n")
	}
	output.WriteString("const checked: Component<SolidRouteProps<Props>> = Screen\n")
	output.WriteString("export default checked\n")
	return output.String(), nil
}

func emitCatalog(catalog string, features []candidate) (string, error) {
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("import type { SolidFeatureCatalog } from '@iota-uz/sdk/solid'\n\n")
	output.WriteString("export const solidFeatures = {\n")
	for _, feature := range features {
		relative, err := filepath.Rel(filepath.Dir(catalog), feature.generated)
		if err != nil {
			return "", err
		}
		importPath := filepath.ToSlash(strings.TrimSuffix(relative, filepath.Ext(relative)))
		if !strings.HasPrefix(importPath, ".") {
			importPath = "./" + importPath
		}
		fmt.Fprintf(&output, "  %q: () => import(%q),\n", solid.FeatureID(feature.packagePath, feature.source), importPath)
	}
	output.WriteString("} satisfies SolidFeatureCatalog\n")
	return output.String(), nil
}

type typeEmitter struct {
	active map[types.Type]bool
}

func (emitter *typeEmitter) emit(value types.Type) (string, error) {
	value = types.Unalias(value)
	if value == nil {
		return "never", errors.New("unresolved Go type")
	}
	if emitter.active[value] {
		return "never", fmt.Errorf("recursive type %s is unsupported in Solid wire contracts", value.String())
	}
	switch typed := value.(type) {
	case *types.Pointer:
		inner, err := emitter.emit(typed.Elem())
		return inner + " | null", err
	case *types.Basic:
		return emitBasic(typed)
	case *types.Slice:
		if basic, ok := types.Unalias(typed.Elem()).(*types.Basic); ok && basic.Kind() == types.Byte {
			return "string", nil
		}
		inner, err := emitter.emit(typed.Elem())
		return "Array<" + inner + ">", err
	case *types.Array:
		inner, err := emitter.emit(typed.Elem())
		return "Array<" + inner + ">", err
	case *types.Map:
		key, ok := types.Unalias(typed.Key()).(*types.Basic)
		if !ok || key.Kind() != types.String {
			return "never", fmt.Errorf("map key %s is unsupported; JSON object keys must be strings", typed.Key())
		}
		inner, err := emitter.emit(typed.Elem())
		return "Record<string, " + inner + ">", err
	case *types.Interface:
		return "unknown", nil
	case *types.Named:
		if known, ok := knownNamed(typed); ok {
			return known, nil
		}
		if enum := stringEnum(typed); len(enum) > 0 {
			quoted := make([]string, len(enum))
			for index, value := range enum {
				quoted[index] = strconv.Quote(value)
			}
			return strings.Join(quoted, " | "), nil
		}
		if methodName, ok := customWireMarshaler(typed); ok {
			return "never", fmt.Errorf("named type %s defines %s; use an explicit wire field type", typed.Obj().Name(), methodName)
		}
		return emitter.emit(typed.Underlying())
	case *types.Struct:
		emitter.active[value] = true
		defer delete(emitter.active, value)
		fields := make([]string, 0, typed.NumFields())
		for index := 0; index < typed.NumFields(); index++ {
			field := typed.Field(index)
			if !field.Exported() {
				continue
			}
			if field.Anonymous() {
				return "never", fmt.Errorf("embedded field %s is unsupported; use an explicit wire struct", field.Name())
			}
			name, optional, asString, skip := jsonField(field.Name(), typed.Tag(index))
			if skip {
				continue
			}
			fieldType := "string"
			var err error
			if !asString {
				fieldType, err = emitter.emit(field.Type())
				if err != nil {
					return "never", fmt.Errorf("field %s: %w", field.Name(), err)
				}
			}
			if optional && strings.HasSuffix(fieldType, " | null") {
				fieldType = strings.TrimSuffix(fieldType, " | null")
			}
			fields = append(fields, fmt.Sprintf("%s%s: %s", strconv.Quote(name), map[bool]string{true: "?"}[optional], fieldType))
		}
		if len(fields) == 0 {
			return "Record<string, never>", nil
		}
		return "{ " + strings.Join(fields, "; ") + " }", nil
	default:
		return "never", fmt.Errorf("go type %s is unsupported in Solid wire contracts", value.String())
	}
}

func customWireMarshaler(named *types.Named) (string, bool) {
	methods := types.NewMethodSet(types.NewPointer(named))
	for index := 0; index < methods.Len(); index++ {
		name := methods.At(index).Obj().Name()
		if name == "MarshalJSON" || name == "MarshalText" {
			return name, true
		}
	}
	return "", false
}

func emitBasic(basic *types.Basic) (string, error) {
	switch {
	case basic.Info()&types.IsBoolean != 0:
		return "boolean", nil
	case basic.Info()&(types.IsInteger|types.IsFloat) != 0:
		return "number", nil
	case basic.Info()&types.IsString != 0:
		return "string", nil
	case basic.Kind() == types.UntypedNil:
		return "null", nil
	default:
		return "never", fmt.Errorf("basic Go type %s is unsupported", basic.Name())
	}
}

func knownNamed(named *types.Named) (string, bool) {
	object := named.Obj()
	if object.Pkg() == nil {
		return "", false
	}
	qualified := object.Pkg().Path() + "." + object.Name()
	switch qualified {
	case "time.Time", "github.com/google/uuid.UUID":
		return "string", true
	case "encoding/json.RawMessage":
		return "unknown", true
	}
	return "", false
}

func stringEnum(named *types.Named) []string {
	basic, ok := named.Underlying().(*types.Basic)
	if !ok || basic.Info()&types.IsString == 0 || named.Obj().Pkg() == nil {
		return nil
	}
	values := make([]string, 0)
	for _, name := range named.Obj().Pkg().Scope().Names() {
		constant, ok := named.Obj().Pkg().Scope().Lookup(name).(*types.Const)
		if !ok || !types.Identical(types.Unalias(constant.Type()), named) {
			continue
		}
		value := constant.Val().ExactString()
		if unquoted, err := strconv.Unquote(value); err == nil {
			values = append(values, unquoted)
		}
	}
	sort.Strings(values)
	return values
}

func jsonField(fallback, raw string) (string, bool, bool, bool) {
	tag := reflect.StructTag(raw).Get("json")
	parts := strings.Split(tag, ",")
	name := fallback
	if len(parts) > 0 && parts[0] != "" {
		name = parts[0]
	}
	if name == "-" {
		return "", false, false, true
	}
	optional := false
	asString := false
	for _, option := range parts[1:] {
		switch option {
		case "omitempty", "omitzero":
			optional = true
		case "string":
			asString = true
		}
	}
	return name, optional, asString, false
}

func namespace(method string) string {
	if index := strings.IndexByte(method, '.'); index > 0 {
		return method[:index]
	}
	return ""
}

func stringArray(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = strconv.Quote(value)
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func reconcile(root string, expected map[string][]byte, check bool) error {
	stale := make([]string, 0)
	err := filepath.WalkDir(root, func(file string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			switch entry.Name() {
			case ".git", "node_modules", "vendor", "dist", ".worktrees":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(file, ".solid.generated.ts") {
			return nil
		}
		if _, exists := expected[file]; exists {
			return nil
		}
		contents, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(contents, []byte(generatedHeader)) {
			stale = append(stale, file)
		}
		return nil
	})
	if err != nil {
		return err
	}
	changed := make([]string, 0)
	for file, contents := range expected {
		actual, err := os.ReadFile(file)
		if err == nil && bytes.Equal(actual, contents) {
			continue
		}
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		changed = append(changed, file)
		if check {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(file, contents, 0o644); err != nil {
			return err
		}
	}
	if check && (len(changed) > 0 || len(stale) > 0) {
		return fmt.Errorf("solid generated files are stale; run iota-solid (changed: %s; stale: %s)", joinRelative(root, changed), joinRelative(root, stale))
	}
	if !check {
		for _, file := range stale {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	return nil
}

func joinRelative(root string, files []string) string {
	values := make([]string, len(files))
	for index, file := range files {
		values[index], _ = filepath.Rel(root, file)
		values[index] = filepath.ToSlash(values[index])
	}
	sort.Strings(values)
	return strings.Join(values, ", ")
}

func ExportName(name string) string {
	runes := []rune(name)
	if len(runes) > 0 {
		runes[0] = unicode.ToUpper(runes[0])
	}
	return string(runes)
}
