package catalog

import (
	"bytes"
	"encoding/json"

	"github.com/iota-uz/iota-sdk/pkg/extruntime/manifest"
)

// SnapshotSchema identifies the catalog snapshot document.
const SnapshotSchema = "iota.catalog/1"

// GeneratedHeader is the default value of Snapshot.Generated: the marker that
// tells readers the file is produced, not written.
const GeneratedHeader = "Code generated by cmd/extruntime-catalog; DO NOT EDIT."

// SnapshotSource is one namespace of a catalog snapshot: its resources and
// the native lists it owns. It is exactly what kit generation consumes
// (`iota-ext kit generate --catalog <file>`), so an author can render
// `@iota-kit/<namespace>` without a running server.
type SnapshotSource struct {
	Namespace string              `json:"namespace"`
	Resources []manifest.Resource `json:"resources"`
	Lists     []string            `json:"lists,omitempty"`
}

// Snapshot is a deterministic, serializable picture of a native catalog:
// native entities (with key types and fields), native lists, native events
// and every other native contract (commands, operations, routes, ...) the
// application registered. Sources are sorted by namespace and resources by ID,
// so equal catalogs produce byte-equal documents.
type Snapshot struct {
	Schema    string           `json:"schema"`
	Generated string           `json:"generated"`
	Sources   []SnapshotSource `json:"sources"`
}

// Snapshot renders the native set. Applications with natives of their own call
// it (or the management API's `GET /_ext/manage/catalog/natives`, which does)
// to export what the SDK snapshot does not know.
func (n *NativeSet) Snapshot() Snapshot {
	snap := Snapshot{Schema: SnapshotSchema, Generated: GeneratedHeader, Sources: []SnapshotSource{}}
	for _, s := range n.Sources() {
		res := s.Resources
		if res == nil {
			res = []manifest.Resource{}
		}
		snap.Sources = append(snap.Sources, SnapshotSource{Namespace: s.Namespace, Resources: res, Lists: s.Lists})
	}
	return snap
}

// JSON is the canonical document: two-space indent, no HTML escaping, one
// trailing newline.
func (s Snapshot) JSON() ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(s); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
