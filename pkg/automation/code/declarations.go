package code

import (
	"regexp"
	"sort"
	"strings"

	"github.com/iota-uz/iota-sdk/pkg/automation/expr"
)

// declarationsEnv is the fixed part of the declarations: env and the result.
const declarationsEnv = `interface CodeFetchInit {
  method?: string;
  headers?: Record<string, string>;
  body?: string;
  redirect?: "follow" | "manual" | "error";
}

interface CodeFetchResponse {
  readonly status: number;
  readonly statusText: string;
  readonly ok: boolean;
  readonly headers: Readonly<Record<string, string>>;
  readonly url: string;
  readonly redirected: boolean;
  text(): Promise<string>;
  json(): Promise<unknown>;
}

interface CodeEnv {
  /** HTTPS only, through the network policy; a refused request throws a NetworkBlocked error. */
  fetch(url: string, init?: CodeFetchInit): Promise<CodeFetchResponse>;
  /** Only the secrets the node declares. */
  readonly secrets: Readonly<Record<SecretName, string>>;
  log(...args: unknown[]): void;
  readonly crypto: {
    randomUUID(): string;
    digest(alg: "SHA-256", data: string): Promise<string>;
  };
}

type CodeResult<O extends string> = { outcome: O; output?: unknown };

/** The signature the code exports: export default async function run(ctx, env) { ... } */
type CodeRun = (ctx: AutomationContext, env: CodeEnv) => Promise<CodeResult<Outcome>>;
`

var tsIdent = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// Declarations is the .d.ts the editor loads next to a Code node: AutomationContext (the node's scope,
// read-only), Outcome and SecretName (the node's outcomes and declared secrets), CodeEnv and
// CodeResult<Outcome>. The declarations are global, so the node's module sees them without an import.
func Declarations(scope expr.Scope, outcomes []string, secrets []string) string {
	var b strings.Builder
	b.WriteString("// Generated by pkg/automation/code for a Code node. Do not edit.\n\n")

	b.WriteString("interface AutomationContext {\n")
	names := make([]string, 0, len(scope.Vars))
	for name := range scope.Vars {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		writeProp(&b, "  ", name, scope.Vars[name])
	}
	b.WriteString("}\n\n")

	b.WriteString("type Outcome = " + literalUnion(outcomes) + ";\n")
	b.WriteString("type SecretName = " + literalUnion(secrets) + ";\n\n")
	b.WriteString(declarationsEnv)
	return b.String()
}

func literalUnion(values []string) string {
	seen := map[string]bool{}
	var parts []string
	for _, v := range values {
		if seen[v] {
			continue
		}
		seen[v] = true
		parts = append(parts, string(quoteJSON(v)))
	}
	if len(parts) == 0 {
		return "never"
	}
	return strings.Join(parts, " | ")
}

func propName(name string) string {
	if tsIdent.MatchString(name) {
		return name
	}
	return string(quoteJSON(name))
}

func writeProp(b *strings.Builder, indent, name string, f expr.Field) {
	optional := f.Kind == expr.Optional
	b.WriteString(indent + "readonly " + propName(name))
	if optional {
		b.WriteString("?")
	}
	b.WriteString(": " + tsType(f, indent) + ";\n")
}

// tsType is the TypeScript type of a JSON value of the field, read-only as the frozen ctx is.
func tsType(f expr.Field, indent string) string {
	switch f.Kind {
	case expr.String:
		return "string"
	case expr.Timestamp:
		return "string /* RFC 3339 */"
	case expr.Int, expr.Double:
		return "number"
	case expr.Bool:
		return "boolean"
	case expr.Enum:
		return literalUnion(f.Enum)
	case expr.List:
		return "ReadonlyArray<" + elemType(f, indent) + ">"
	case expr.Map:
		return "Readonly<Record<string, " + elemType(f, indent) + ">>"
	case expr.Optional:
		return elemType(f, indent) + " | null"
	case expr.Object:
		if len(f.Props) == 0 {
			return "{}"
		}
		var b strings.Builder
		b.WriteString("{\n")
		for _, p := range f.Props {
			writeProp(&b, indent+"  ", p.Name, p.Field)
		}
		b.WriteString(indent + "}")
		return b.String()
	}
	return "any"
}

func elemType(f expr.Field, indent string) string {
	if f.Elem == nil {
		return "any"
	}
	return tsType(*f.Elem, indent)
}
