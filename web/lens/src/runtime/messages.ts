/**
 * The runtime's own translations of its chrome.
 *
 * A host sends `document.i18n` and wins over everything here. Without this
 * layer a host that translated only a handful of keys (or none) got English
 * «Updated», «Export», «Total», «Hide all» on an otherwise Russian board,
 * because every call site only carries an English fallback. The catalogue is
 * keyed by the primary language subtag of `document.meta.locale`; English is
 * the call-site fallback itself and needs no entry.
 *
 * Report editor and print-report strings are left to the host catalogue: they
 * are administrative surfaces that a host already has to word for its domain.
 */
export type MessageCatalogue = Readonly<Record<string, string>>

