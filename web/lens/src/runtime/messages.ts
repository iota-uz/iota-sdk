const catalogues: Readonly<Record<string, MessageCatalogue>> = { ru, uz }

/** The built-in text for `key` in `locale`, or undefined when there is none. */
export function builtinMessage(locale: string | undefined, key: string): string | undefined {
  if (!locale) return undefined
  const [primary, ...subtags] = locale.split(/[-_]/)
  // The Uzbek catalogue is Latin; a Cyrillic reader gets the call-site text
  // rather than a script they did not ask for.
  if (subtags.some((tag) => tag.toLowerCase() === 'cyrl')) return undefined
  return primary ? catalogues[primary.toLowerCase()]?.[key] : undefined
}
